package com.smartfridge.config;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Locale;
import javax.sql.DataSource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.BeansException;
import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.stereotype.Component;

/**
 * Idempotent, repeatable database migration for Multi-List persistence.
 * Runs before JPA/Hibernate initializes to ensure existing unparented
 * shopping_list_items rows are assigned to the default 'Main Shopping List'
 * before Hibernate validates or enforces NOT NULL constraints.
 */
@Component
public class MultiListDatabaseMigration implements BeanPostProcessor {

    private static final Logger log = LoggerFactory.getLogger(MultiListDatabaseMigration.class);

    @Override
    public Object postProcessAfterInitialization(Object bean, String beanName) throws BeansException {
        if (bean instanceof DataSource dataSource) {
            log.info("Running MultiListDatabaseMigration on DataSource bean: {}", beanName);
            runMigration(dataSource);
        }
        return bean;
    }

    public synchronized void runMigration(DataSource dataSource) {
        try (Connection conn = dataSource.getConnection()) {
            boolean autoCommit = conn.getAutoCommit();
            conn.setAutoCommit(false);
            try {
                DatabaseMetaData meta = conn.getMetaData();

                // 1. Ensure shopping_lists table exists
                boolean shoppingListsExists = tableExists(meta, "shopping_lists");
                if (!shoppingListsExists) {
                    log.info("Creating table 'shopping_lists'...");
                    try (Statement stmt = conn.createStatement()) {
                        stmt.execute("""
                            CREATE TABLE shopping_lists (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                title VARCHAR(120) NOT NULL,
                                color VARCHAR(30) NOT NULL,
                                icon VARCHAR(30) NOT NULL,
                                is_archived BOOLEAN NOT NULL DEFAULT FALSE,
                                is_default BOOLEAN NOT NULL DEFAULT FALSE,
                                created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                                updated_at TIMESTAMP WITH TIME ZONE NOT NULL
                            )
                        """);
                    }
                }

                // 2. Ensure default 'Main Shopping List' exists and get its ID
                Long defaultListId = getOrCreateDefaultListId(conn);
                log.info("Default 'Main Shopping List' verified with ID: {}", defaultListId);

                // 3. Inspect shopping_list_items table if it exists
                boolean itemsTableExists = tableExists(meta, "shopping_list_items");
                if (itemsTableExists) {
                    boolean columnExists = columnExists(meta, "shopping_list_items", "shopping_list_id");
                    if (!columnExists) {
                        log.info("Adding column 'shopping_list_id' to 'shopping_list_items'...");
                        try (Statement stmt = conn.createStatement()) {
                            stmt.execute("ALTER TABLE shopping_list_items ADD COLUMN shopping_list_id BIGINT");
                        }
                    }

                    // 4. Migrate any existing unparented rows to default list
                    try (PreparedStatement updateStmt = conn.prepareStatement(
                            "UPDATE shopping_list_items SET shopping_list_id = ? WHERE shopping_list_id IS NULL")) {
                        updateStmt.setLong(1, defaultListId);
                        int migratedCount = updateStmt.executeUpdate();
                        if (migratedCount > 0) {
                            log.info("Successfully migrated {} legacy unparented shopping item(s) to default list ID {}",
                                    migratedCount, defaultListId);
                        }
                    }

                    // 5. Enforce NOT NULL constraint
                    try (Statement stmt = conn.createStatement()) {
                        stmt.execute("ALTER TABLE shopping_list_items ALTER COLUMN shopping_list_id SET NOT NULL");
                    } catch (SQLException e) {
                        log.debug("Column shopping_list_id may already be NOT NULL: {}", e.getMessage());
                    }

                    // 6. Create index on shopping_list_id
                    try (Statement stmt = conn.createStatement()) {
                        stmt.execute("CREATE INDEX IF NOT EXISTS idx_shopping_list_items_list ON shopping_list_items(shopping_list_id)");
                    } catch (SQLException e) {
                        log.debug("Index idx_shopping_list_items_list creation note: {}", e.getMessage());
                    }

                    // 7. Add foreign key constraint if possible
                    try (Statement stmt = conn.createStatement()) {
                        stmt.execute("""
                            ALTER TABLE shopping_list_items ADD CONSTRAINT fk_shopping_list_items_list
                            FOREIGN KEY (shopping_list_id) REFERENCES shopping_lists(id)
                        """);
                    } catch (SQLException e) {
                        log.debug("Foreign key constraint fk_shopping_list_items_list may already exist: {}", e.getMessage());
                    }
                }

                conn.commit();
                log.info("MultiListDatabaseMigration completed successfully.");
            } catch (Exception e) {
                conn.rollback();
                log.error("MultiListDatabaseMigration failed, rolled back.", e);
                throw new IllegalStateException("Database migration failed: " + e.getMessage(), e);
            } finally {
                conn.setAutoCommit(autoCommit);
            }
        } catch (SQLException e) {
            log.error("Failed to acquire connection for migration", e);
            throw new IllegalStateException("Database migration connection error: " + e.getMessage(), e);
        }
    }

    private Long getOrCreateDefaultListId(Connection conn) throws SQLException {
        try (Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(
                     "SELECT id FROM shopping_lists WHERE is_default = TRUE OR LOWER(title) = 'main shopping list' ORDER BY id ASC")) {
            if (rs.next()) {
                return rs.getLong("id");
            }
        }

        try (PreparedStatement insertStmt = conn.prepareStatement(
                """
                INSERT INTO shopping_lists (title, color, icon, is_archived, is_default, created_at, updated_at)
                VALUES ('Main Shopping List', '#0b292f', 'shopping-bag', FALSE, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
                """,
                Statement.RETURN_GENERATED_KEYS)) {
            insertStmt.executeUpdate();
            try (ResultSet genKeys = insertStmt.getGeneratedKeys()) {
                if (genKeys.next()) {
                    return genKeys.getLong(1);
                }
            }
        }

        try (Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT id FROM shopping_lists WHERE is_default = TRUE ORDER BY id ASC")) {
            if (rs.next()) {
                return rs.getLong("id");
            }
        }

        throw new SQLException("Could not retrieve generated ID for default shopping list.");
    }

    private boolean tableExists(DatabaseMetaData meta, String tableName) throws SQLException {
        try (ResultSet rs = meta.getTables(null, null, "%", new String[]{"TABLE"})) {
            while (rs.next()) {
                String name = rs.getString("TABLE_NAME");
                if (name != null && name.equalsIgnoreCase(tableName)) {
                    return true;
                }
            }
        }
        return false;
    }

    private boolean columnExists(DatabaseMetaData meta, String tableName, String columnName) throws SQLException {
        try (ResultSet rs = meta.getColumns(null, null, "%", "%")) {
            while (rs.next()) {
                String tName = rs.getString("TABLE_NAME");
                String cName = rs.getString("COLUMN_NAME");
                if (tName != null && tName.equalsIgnoreCase(tableName)
                        && cName != null && cName.equalsIgnoreCase(columnName)) {
                    return true;
                }
            }
        }
        return false;
    }
}
